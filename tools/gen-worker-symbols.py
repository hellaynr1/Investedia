"""Writes workers/live/symbols.js: the assets the price Worker refreshes. It is built from the SAME mapping the GitHub robot uses
(update_market.py: site_symbols(), YAHOO, FRED, YIELDS, CENTS), so a site symbol means exactly the same instrument in both places.
Excluded on purpose: crypto (streams through /ticker) and bond yields (FRED / basis-point changes stay on the robot).
For every symbol it fetches Yahoo's spark feed once and compares it with assets/quotes.js to learn the unit scale (1, or 0.01 for pence/cents quotes);
symbols whose Worker price would not match the static price are listed and left out, never guessed.
Run: python3 tools/gen-worker-symbols.py"""
import json, re, sys, urllib.parse, urllib.request
sys.path.insert(0, '.')
import update_market as um
q = json.loads(re.sub(r'^window\.QUOTES=', '', open('assets/quotes.js').read().strip().rstrip(';')))['q']
rows = []
for s in um.site_symbols():
    y = um.YAHOO.get(s, s)
    if s in um.FRED or s in um.YIELDS or y.endswith('-USD') or s not in q: continue
    rows.append((s, y))
def group(s, y):
    if y.endswith('=X') or y.startswith('DX-Y'): return 'f'
    if y.endswith('=F') and s not in ('ES1', 'YM1', 'NQ1'): return 'c'
    if y.startswith('^') or s in ('ES1', 'YM1', 'NQ1', 'FTSEMIB', 'XJO', 'TA35', 'SSEC') or y in ('000001.SS', 'FTSEMIB.MI', 'TA35.TA'): return 'i'
    return 's'
raw = {}
for i in range(0, len(rows), 20):
    ys = [y for _, y in rows[i:i + 20]]
    u = 'https://query1.finance.yahoo.com/v8/finance/spark?range=1d&interval=1d&symbols=' + urllib.parse.quote(','.join(ys))
    try:
        d = json.loads(urllib.request.urlopen(urllib.request.Request(u, headers={'User-Agent': 'Mozilla/5.0 (Investedia)'}), timeout=25).read())
        for k, v in d.items():
            c = [x for x in (v.get('close') or []) if isinstance(x, (int, float)) and x > 0]
            if c: raw[k] = c[-1]
    except Exception as e: print('spark batch failed', i, e)
out, skipped = [], []
for s, y in rows:
    r, st = raw.get(y), q[s]['p']
    if not r or not st: skipped.append((s, y, 'no spark price')); continue
    ratio = r / st
    k = 0.01 if 90 < ratio < 110 else 1 if 0.9 < ratio < 1.1 else None  # within 10% (the static file may be a few minutes older)
    if k is None: skipped.append((s, y, f'ratio {ratio:.2f}')); continue
    out.append(f"{s}|{y}|0|{group(s, y)}|{k}")
open('workers/live/symbols.js', 'w').write('// Generated by tools/gen-worker-symbols.py from update_market.py. Format: site symbol | Yahoo symbol | 1 if the change is inverted | group (i indices, s stocks, f currencies, c commodities) | price scale.\nexport const TIER_A = ' + json.dumps(out) + ';\nexport const TIER_B = [];\n')
print(len(out), 'symbols written;', len(skipped), 'left out:', skipped)
