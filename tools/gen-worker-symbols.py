"""Write workers/live/symbols.js: the list of non-crypto assets the price Worker refreshes (crypto streams through /ticker).
Tier A (indices, commodities, major currency pairs, the first 40 companies) is refreshed more often than tier B (everything else).
Run after adding assets: python3 tools/gen-worker-symbols.py"""
import json
d = json.load(open('assets/globe/markets.json'))['assets']
ysym = lambda a: a['s'] + '=X' if a['t'] == 'fx' else a['s']
rows = [a for a in d if a['t'] != 'crypto']
fx = [a for a in rows if a['t'] == 'fx']
A, B = [], []
for a in rows:
    prio = a.get('g') == 'Index' or a['t'] == 'cmd' or (a['t'] == 'fx' and a in fx[:20]) or (a['t'] == 'stocks' and a.get('g') not in ('Index',) and a in [x for x in rows if x['t'] == 'stocks' and x.get('g') != 'Index'][:40])
    (A if prio else B).append(a)
enc = lambda a: f"{a['s']}|{ysym(a)}|{1 if a.get('inv') else 0}"
open('workers/live/symbols.js', 'w').write('// Generated by tools/gen-worker-symbols.py. Format: site symbol | Yahoo symbol | 1 if the day change is inverted.\nexport const TIER_A = ' + json.dumps([enc(a) for a in A]) + ';\nexport const TIER_B = ' + json.dumps([enc(a) for a in B]) + ';\n')
print(len(A), len(B))
