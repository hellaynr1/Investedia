"""Writes the reference data the news Worker needs, from the same Python sources the GitHub robot uses (no drift):
workers/live/v1/ref.js    ISO2 -> [country name, region key], ticker -> site symbol, category list
workers/live/v1/feeds.js  priority-tier feeds (official + fast publishers), and the Gemini prompt text
Run after changing feeds, countries or the prompt: python3 tools/gen-worker-news-ref.py"""
import json, os, sys
os.environ.setdefault('GEMINI_API_KEY', '')
sys.path.insert(0, '.')
import update_globe_news as u
box, by_iso, sym = u.load_ref()
ref = {c: [n, u.REGION.get(c, 'eu')] for c, n in by_iso.items()}
open('workers/live/v1/ref.js', 'w').write('// Generated by tools/gen-worker-news-ref.py. Do not edit.\nexport const COUNTRIES = ' + json.dumps(ref, ensure_ascii=False, separators=(',', ':')) + ';\nexport const SYM = ' + json.dumps(sym, separators=(',', ':')) + ';\nexport const CATS = ' + json.dumps(u.CATS) + ';\n')
feeds = [{'url': x, 'name': n, 'hint': h, 'kind': 'official'} for x, n, h in u.FEEDS] + [{'url': x, 'name': n, 'hint': '', 'kind': 'news'} for x, n in u.NEWS_FEEDS if n in u.PRIORITY_NEWS]
prompt = u.PROMPT.replace('{{', '\u0001').replace('}}', '\u0002')
prompt = prompt.replace('\u0001', '{').replace('\u0002', '}')
open('workers/live/v1/feeds.js', 'w').write('// Generated by tools/gen-worker-news-ref.py. Do not edit.\nexport const FEEDS = ' + json.dumps(feeds, ensure_ascii=False, indent=0) + ';\nexport const PROMPT = ' + json.dumps(prompt, ensure_ascii=False) + ';\n')
print(len(ref), 'countries', len(sym), 'symbols', len(feeds), 'feeds')
